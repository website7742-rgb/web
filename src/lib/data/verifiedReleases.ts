export function getVerifiedReleases(): Release[] {
  return VERIFIED_HIPHOP_RELEASES;
}

export function getReleaseBySlugOrId(slugOrId: string): Release | undefined {
  if (!slugOrId) return undefined;
  const normalized = decodeURIComponent(slugOrId).toLowerCase().trim();
  return VERIFIED_HIPHOP_RELEASES.find(
    (r) =>
      r.id.toLowerCase() === normalized ||
      (r.slug && r.slug.toLowerCase().trim() === normalized)
  );
}

export function getTracksForRelease(releaseIdOrTitle: string): Track[] {
  if (!releaseIdOrTitle) return [];
  const normalized = decodeURIComponent(releaseIdOrTitle).toLowerCase().trim();
  return VERIFIED_RELEASE_TRACKS.filter(
    (t) =>
      t.releaseId.toLowerCase() === normalized ||
      t.releaseTitle.toLowerCase().trim() === normalized
  );
}
